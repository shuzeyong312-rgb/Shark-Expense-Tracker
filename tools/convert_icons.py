from pathlib import Path
import re
import xml.etree.ElementTree as ET

root = Path(__file__).resolve().parents[1]
source = (root / 'docs/prototypes/final-prototype.html').read_text(encoding='utf-8')
body = source.split('function iconSvg(name){', 1)[1].split(' return `<svg', 1)[0]
icons = dict(re.findall(r'^\s*(\w+):`(.*?)`,?\s*$', body, re.M))
for page in ('home', 'chart', 'agent', 'mine'):
    markup = re.search(r'<button class="nav-item[^\"]*" data-page="' + page + r'"[^>]*>\s*<svg[^>]*>(.*?)</svg>', source).group(1)
    icons['nav_' + page] = markup
icons['settings'] = re.search(r'function settingsCategorySvg\(\).*?<svg[^>]*>(.*?)</svg>', source).group(1)
for cls in ('agent-mark', 'agent-avatar'):
    icons[cls.replace('-', '_')] = re.search(r'<div class="' + cls + r'"[^>]*>\s*<svg[^>]*>(.*?)</svg>', source, re.S).group(1)
common = 'fill="none" stroke="#292929" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round"'
yellow = 'fill="#ffda43" stroke="#292929" stroke-width="1.7" stroke-linejoin="round"'
ns = 'http://schemas.android.com/apk/res/android'
ET.register_namespace('android', ns)
def attr(element, key, value): element.set(f'{{{ns}}}{key}', str(value))
def path_for(node):
    a = node.attrib
    if node.tag == 'path': return a['d']
    if node.tag == 'circle':
        x,y,r = map(float, (a['cx'],a['cy'],a['r']))
        return f'M{x-r},{y} a{r},{r} 0 1,0 {2*r},0 a{r},{r} 0 1,0 {-2*r},0'
    if node.tag == 'rect':
        x,y,w,h = (float(a.get(k, 0)) for k in ('x','y','width','height'))
        r = min(float(a.get('rx', 0)), w/2, h/2)
        if not r: return f'M{x},{y} h{w} v{h} h{-w} Z'
        return f'M{x+r},{y} h{w-2*r} a{r},{r} 0 0,1 {r},{r} v{h-2*r} a{r},{r} 0 0,1 {-r},{r} h{-w+2*r} a{r},{r} 0 0,1 {-r},{-r} v{-h+2*r} a{r},{r} 0 0,1 {r},{-r} Z'
    if node.tag == 'text' and node.text == '8':
        # The prototype's single text glyph is converted into two outlined loops.
        return 'M12,8.5 C9.5,8.5 9.5,11.5 12,11.5 C14.5,11.5 14.5,8.5 12,8.5 Z M12,11.5 C9,11.5 9,15 12,15 C15,15 15,11.5 12,11.5 Z'
    raise ValueError(f'Unsupported SVG element: {node.tag}')

for name, markup in icons.items():
    markup = markup.replace('${common}', common).replace('${yellow}', yellow)
    svg = ET.fromstring('<svg>' + markup + '</svg>')
    for outline in (False, True):
        vector = ET.Element('vector')
        for k,v in [('width','24dp'),('height','24dp'),('viewportWidth','24'),('viewportHeight','24')]: attr(vector,k,v)
        for node in svg:
            parent = vector
            if 'transform' in node.attrib:
                match = re.fullmatch(r'rotate\((-?[\d.]+) ([\d.]+) ([\d.]+)\)', node.attrib['transform'])
                if not match: raise ValueError(node.attrib['transform'])
                parent = ET.SubElement(vector,'group')
                for k,v in zip(('rotation','pivotX','pivotY'), match.groups()): attr(parent,k,v)
            p = ET.SubElement(parent,'path')
            attr(p,'pathData',path_for(node))
            fill = node.get('fill', '#000000')
            stroke = node.get('stroke')
            if name.startswith(('nav_', 'agent_')):
                fill, stroke = 'none', '#292929'
                node.set('stroke-width', '1.8')
                node.set('stroke-linecap', 'round')
                node.set('stroke-linejoin', 'round')
            if node.tag == 'text': fill, stroke = 'none', '#626262'
            if outline:
                if fill.lower() == '#ffda43': fill = 'none'
                if stroke and stroke.lower() == '#292929': stroke = '#626262'
            if fill != 'none': attr(p,'fillColor',fill)
            if stroke and stroke != 'none': attr(p,'strokeColor',stroke)
            if stroke: attr(p,'strokeWidth',node.get('stroke-width','1') if node.tag != 'text' else '0.8')
            if node.get('stroke-linecap'): attr(p,'strokeLineCap',node.get('stroke-linecap'))
            if node.get('stroke-linejoin'): attr(p,'strokeLineJoin',node.get('stroke-linejoin'))
        target = root / 'app/src/main/res/drawable' / f'ic_cat_{name}_{"outline" if outline else "filled"}.xml'
        ET.ElementTree(vector).write(target, encoding='utf-8', xml_declaration=True)
print(f'Converted {len(icons)} icons to {len(icons)*2} vectors')
lines = ['package com.example.personalledger', '', '// Generated by tools/convert_icons.py from the frozen prototype.', 'fun iconResource(key: String, outline: Boolean): Int = when (key) {']
for name in sorted(icons):
    lines.append(f'    "{name}" -> if (outline) R.drawable.ic_cat_{name}_outline else R.drawable.ic_cat_{name}_filled')
lines += ['    else -> 0', '}', '']
(root / 'app/src/main/java/com/example/personalledger/IconResources.kt').write_text('\n'.join(lines), encoding='utf-8')
